def pad_and_average(histories, key):
    max_len = max(len(h[key]) for h in histories)
    padded = []
    for h in histories:
        arr = np.array(h[key])
        if len(arr) < max_len:
            arr = np.pad(arr, (0, max_len - len(arr)), mode='edge')
        padded.append(arr)
    return np.mean(padded, axis=0), np.std(padded, axis=0)


def plot_curves(histories_dict, dataset_name):
    models = list(histories_dict.keys())
    fig, axes = plt.subplots(1, 3, figsize=(18, 5))

    metrics = [
        ('train_loss', 'Train Loss'),
        ('val_loss',   'Validation Loss'),
        ('val_acc',    'Validation Accuracy')
    ]

    for ax, (key, title) in zip(axes, metrics):
        for model_name in models:
            mean, std = pad_and_average(histories_dict[model_name], key)
            epochs = np.arange(1, len(mean) + 1)
            ax.plot(epochs, mean, label=model_name)
            ax.fill_between(epochs, mean - std, mean + std, alpha=0.15)
        ax.set_title(f"{title}\n{dataset_name} | 60-20-20")
        ax.set_xlabel("Epoch")
        ax.legend(fontsize=7)
        ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.show()


for ds_name in all_histories:
    plot_curves(all_histories[ds_name], ds_name)

