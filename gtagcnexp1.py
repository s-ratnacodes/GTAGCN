def prepare_graph(data):
    if MAKE_UNDIRECTED:
        data.edge_index = to_undirected(data.edge_index, num_nodes=data.num_nodes)
    return data


def safe_stratify(y):
    counts = np.bincount(y)
    counts = counts[counts > 0]
    return y if counts.min() >= 2 else None


def create_random_split(data, ratios, seed):
    train_ratio, val_ratio, test_ratio = ratios
    n = data.num_nodes
    indices = np.arange(n)
    y = data.y.cpu().numpy()

    train_val_idx, test_idx = train_test_split(
        indices, test_size=test_ratio, random_state=seed, stratify=safe_stratify(y)
    )
    train_idx, val_idx = train_test_split(
        train_val_idx,
        test_size=val_ratio / (train_ratio + val_ratio),
        random_state=seed,
        stratify=safe_stratify(y[train_val_idx])
    )

    data = data.clone()
    for mask_name, idx in [('train_mask', train_idx), ('val_mask', val_idx), ('test_mask', test_idx)]:
        mask = torch.zeros(n, dtype=torch.bool)
        mask[idx] = True
        setattr(data, mask_name, mask)
    return data


def get_data(raw_data, ratios, run):
    data = raw_data.clone()
    if ratios is None:
        for mask_name in ('train_mask', 'val_mask', 'test_mask'):
            mask = getattr(data, mask_name)
            if mask.dim() == 2:
                setattr(data, mask_name, mask[:, run % mask.size(1)])
    else:
        data = create_random_split(data, ratios, SEED + run)
    return data.to(device)


