class GCNII(nn.Module):
    def __init__(self, in_channels, hidden_channels, out_channels, num_layers=GCNII_LAYERS):
        super().__init__()
        self.lins = nn.ModuleList([
            nn.Linear(in_channels, hidden_channels),
            nn.Linear(hidden_channels, out_channels)
        ])
        self.convs = nn.ModuleList([
            GCN2Conv(hidden_channels, alpha=ALPHA_GCN2, theta=THETA_GCN2, layer=i + 1)
            for i in range(num_layers)
        ])

    def forward(self, x, edge_index):
        x = apply_input_dropout(x, self.training)
        x = x0 = self.lins[0](x).relu()
        for conv in self.convs:
            x = F.dropout(x, p=DROPOUT, training=self.training)
            x = conv(x, x0, edge_index).relu()
        x = F.dropout(x, p=DROPOUT, training=self.training)
        return self.lins[1](x)


