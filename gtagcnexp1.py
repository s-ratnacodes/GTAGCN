class TAGConv1(MessagePassing):
    def __init__(self, in_channels, out_channels, K=3, bias=True, normalize=True,
                 use_mlp=False, use_message_relu=True, eps=1e-7, **kwargs):
        kwargs.setdefault('aggr', 'add')
        super().__init__(**kwargs)

        self.K = K
        self.normalize = normalize
        self.use_mlp = use_mlp
        self.use_message_relu = use_message_relu
        self.eps = eps

        self.lins = nn.ModuleList([
            Linear(in_channels, out_channels, bias=False) for _ in range(K + 1)
        ])
        self.comb = nn.Parameter(torch.ones(K + 1))

        if bias:
            self.bias = nn.Parameter(torch.zeros(out_channels))
        else:
            self.register_parameter('bias', None)

        self.mlp = nn.Sequential(Linear(out_channels, out_channels), nn.ReLU()) if use_mlp else nn.Identity()
        self.reset_parameters()

    def reset_parameters(self):
        for lin in self.lins:
            lin.reset_parameters()
        nn.init.ones_(self.comb)
        if self.bias is not None:
            zeros(self.bias)

    def forward(self, x, edge_index, edge_weight=None):
        if self.normalize:
            edge_index, edge_weight = gcn_norm(
                edge_index, edge_weight, x.size(self.node_dim),
                improved=False, add_self_loops=False,
                flow=self.flow, dtype=x.dtype
            )

        out = self.comb[0] * self.lins[0](x)
        h = x
        for k in range(1, self.K + 1):
            h = self.propagate(edge_index, x=h, edge_weight=edge_weight)
            out = out + self.comb[k] * self.lins[k](h)

        if self.bias is not None:
            out = out + self.bias
        return self.mlp(out)

    def message(self, x_j, edge_weight):
        msg = x_j if edge_weight is None else edge_weight.view(-1, 1) * x_j
        if self.use_message_relu:
            return msg.relu() + self.eps
        return msg

    def message_and_aggregate(self, adj_t, x):
        return spmm(adj_t, x, reduce=self.aggr)


