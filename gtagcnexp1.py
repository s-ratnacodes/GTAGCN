def make_optimizer(model, lr, weight_decay):
    decay, no_decay = [], []
    for name, param in model.named_parameters():
        if not param.requires_grad:
            continue
        if NO_DECAY_HOP_COEFS and ('comb' in name or name.endswith('temp')):
            no_decay.append(param)
        else:
            decay.append(param)
    groups = [{'params': decay, 'weight_decay': weight_decay}]
    if no_decay:
        groups.append({'params': no_decay, 'weight_decay': 0.0})
    return torch.optim.Adam(groups, lr=lr)


def train_one_epoch(model, data, optimizer, criterion):
    model.train()
    optimizer.zero_grad()
    out = model(data.x, data.edge_index)
    loss = criterion(out[data.train_mask], data.y[data.train_mask])
    loss.backward()
    optimizer.step()
    return loss.item()


@torch.no_grad()
def evaluate(model, data, criterion):
    model.eval()
    out = model(data.x, data.edge_index)
    pred = out.argmax(dim=1)
    val_loss = criterion(out[data.val_mask], data.y[data.val_mask]).item()
    val_acc = (pred[data.val_mask] == data.y[data.val_mask]).float().mean().item()
    test_acc = (pred[data.test_mask] == data.y[data.test_mask]).float().mean().item()
    return val_loss, val_acc, test_acc


def run_with_early_stopping(model, data):
    optimizer = make_optimizer(model, LR, WEIGHT_DECAY)
    criterion = nn.CrossEntropyLoss()

    best = {'val_loss': float('inf'), 'val_acc': 0.0, 'test_acc': 0.0, 'epoch': 0}
    patience_counter = 0

    history = {
        'train_loss': [],
        'val_loss': [],
        'val_acc': []
    }

    for epoch in range(1, MAX_EPOCHS + 1):
        train_loss = train_one_epoch(model, data, optimizer, criterion)
        val_loss, val_acc, test_acc = evaluate(model, data, criterion)

        history['train_loss'].append(train_loss)
        history['val_loss'].append(val_loss)
        history['val_acc'].append(val_acc)

        improved = (val_loss < best['val_loss']) if SELECT_BY == 'val_loss' else (val_acc > best['val_acc'])
        if improved:
            best = {'val_loss': val_loss, 'val_acc': val_acc, 'test_acc': test_acc, 'epoch': epoch}
            patience_counter = 0
        else:
            patience_counter += 1
            if patience_counter >= PATIENCE:
                break

    return best['val_acc'], best['test_acc'], history


